-- 관리자 예약 랭킹 화면 /reservation-ranking (2026-10-20)
--
-- 월별(이용일 기준) 확정 예약 횟수를 회원별로 순위 매긴다. 사장님이 월별 리워드에 쓸 예정이라 10월부터 센다.
-- 회원 이름·연락처가 나가므로 관리자 전용 — 서비스단 isAdmin 검사 + URL 매핑 둘 다 둔다.
--
-- mysql 클라이언트로 실행할 때 --default-character-set=utf8mb4 를 붙일 것.
-- **URL 매핑 INSERT 후 앱 재시작 필요** — 매핑 로딩이 @PostConstruct 1회다.

START TRANSACTION;

-- 권한 매핑 — 관리자(1)만. 주소당 역할 하나(권한 계층 규칙)
INSERT INTO BGM_AGIT_URL_RESOURCES (BGM_AGIT_URL_RESOURCES_PATH, BGM_AGIT_URL_HTTP_METHOD, REGIST_DATE)
SELECT '/bgm-agit/reservation/ranking', 'GET', NOW()
  FROM DUAL
 WHERE NOT EXISTS (
       SELECT 1 FROM BGM_AGIT_URL_RESOURCES
        WHERE BGM_AGIT_URL_RESOURCES_PATH = '/bgm-agit/reservation/ranking'
          AND BGM_AGIT_URL_HTTP_METHOD = 'GET');

INSERT INTO BGM_AGIT_URL_RESOURCES_ROLE (BGM_AGIT_ROLE_ID, BGM_AGIT_URL_RESOURCES_ID, REGIST_DATE)
SELECT 1, u.BGM_AGIT_URL_RESOURCES_ID, NOW()
  FROM BGM_AGIT_URL_RESOURCES u
 WHERE u.BGM_AGIT_URL_RESOURCES_PATH = '/bgm-agit/reservation/ranking'
   AND u.BGM_AGIT_URL_HTTP_METHOD = 'GET'
   AND NOT EXISTS (
       SELECT 1 FROM BGM_AGIT_URL_RESOURCES_ROLE r
        WHERE r.BGM_AGIT_URL_RESOURCES_ID = u.BGM_AGIT_URL_RESOURCES_ID);

-- 메뉴 — "예약 현황판" 과 같은 부모·같은 자리 다음에 둔다(관리자 메뉴 묶음)
INSERT INTO BGM_AGIT_MAIN_MENU
       (BGM_AGIT_SUB_MENU_ID, BGM_AGIT_AREA_ID, BGM_AGIT_MENU_NAME, BGM_AGIT_MENU_LINK, BGM_AGIT_USE_STATUS, REGIST_DATE)
SELECT b.BGM_AGIT_SUB_MENU_ID, b.BGM_AGIT_AREA_ID, '예약 랭킹', '/reservation-ranking', 1, NOW()
  FROM BGM_AGIT_MAIN_MENU b
 WHERE b.BGM_AGIT_MENU_LINK = '/reservation-board'
   AND NOT EXISTS (SELECT 1 FROM BGM_AGIT_MAIN_MENU WHERE BGM_AGIT_MENU_LINK = '/reservation-ranking')
 LIMIT 1;

-- 메뉴 권한 — 관리자(1). 없으면 아무에게도 안 보인다(공휴일 메뉴 때 빠뜨렸던 부분)
INSERT INTO BGM_AGIT_MENU_ROLE (BGM_AGIT_ROLE_ID, BGM_AGIT_MAIN_MENU_ID, REGIST_DATE, MODIFY_DATE)
SELECT 1, m.BGM_AGIT_MAIN_MENU_ID, NOW(), NOW()
  FROM BGM_AGIT_MAIN_MENU m
 WHERE m.BGM_AGIT_MENU_LINK = '/reservation-ranking'
   AND NOT EXISTS (
       SELECT 1 FROM BGM_AGIT_MENU_ROLE r
        WHERE r.BGM_AGIT_MAIN_MENU_ID = m.BGM_AGIT_MAIN_MENU_ID AND r.BGM_AGIT_ROLE_ID = 1);

COMMIT;

-- 확인
SELECT u.BGM_AGIT_URL_HTTP_METHOD AS method, u.BGM_AGIT_URL_RESOURCES_PATH AS path,
       GROUP_CONCAT(r.BGM_AGIT_ROLE_ID) AS role_ids
  FROM BGM_AGIT_URL_RESOURCES u
  LEFT JOIN BGM_AGIT_URL_RESOURCES_ROLE r ON r.BGM_AGIT_URL_RESOURCES_ID = u.BGM_AGIT_URL_RESOURCES_ID
 WHERE u.BGM_AGIT_URL_RESOURCES_PATH = '/bgm-agit/reservation/ranking'
 GROUP BY u.BGM_AGIT_URL_RESOURCES_ID, u.BGM_AGIT_URL_HTTP_METHOD, u.BGM_AGIT_URL_RESOURCES_PATH;
SELECT m.BGM_AGIT_MAIN_MENU_ID AS id, m.BGM_AGIT_SUB_MENU_ID AS parent_id, m.BGM_AGIT_MENU_NAME AS name,
       m.BGM_AGIT_MENU_LINK AS link, m.BGM_AGIT_AREA_ID AS area,
       (SELECT GROUP_CONCAT(BGM_AGIT_ROLE_ID) FROM BGM_AGIT_MENU_ROLE r WHERE r.BGM_AGIT_MAIN_MENU_ID = m.BGM_AGIT_MAIN_MENU_ID) AS roles
  FROM BGM_AGIT_MAIN_MENU m
 WHERE m.BGM_AGIT_MENU_LINK IN ('/reservation-board', '/reservation-ranking');

